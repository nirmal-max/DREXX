def test_result_hash_commits_to_confidence_too(image):
    """The ledger must fix how sure the tool was, not only what it found."""
    path, _ = image
    got = carve(str(path))
    h = result_hash(got)
    got[0]["confidence"] = HIGH if got[0]["confidence"] != HIGH else LOW
    assert result_hash(got) != h


def test_extraction_writes_files_matching_their_recorded_digest(image, tmp_path):
    import hashlib
    path, _ = image
    out = tmp_path / "recovered"
    for a in carve(str(path), out_dir=str(out)):
        data = (out / a["filename"]).read_bytes()
        assert hashlib.sha256(data).hexdigest() == a["sha256"]


def test_a_carve_that_recovered_nothing_is_not_VERIFIED():
    """Vacuous truth is the wrong word in a signed field a court reads.

    outcome_for([]) returned VERIFIED because "every extent was confirmed" is trivially
    true of no extents. Correct logic, wrong word: VERIFIED reads as "checked and good",
    not "nothing happened". Found on real CFReDS L2/L3 -- the images NIST built to hold
    no contiguous file -- where the ledger was labelling a zero-recovery run VERIFIED.
    """
    assert outcome_for([]) == "PARTIAL"


def test_the_empty_case_still_uses_the_closed_vocabulary():
    from attestation.core import OUTCOMES
    assert outcome_for([]) in OUTCOMES
